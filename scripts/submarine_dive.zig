// submarine_dive.zig: a yellow submarine visits the fish (never runs)
const std = @import("std");

const Sub = struct {
    depth: u32 = 0,
    fish_seen: u32 = 0,

    fn dive(self: *Sub, meters: u32) void {
        self.depth += meters;
        self.fish_seen += meters / 10;
    }
};

fn bar(pct: u32) [22]u8 {
    var out: [22]u8 = undefined;
    out[0] = '[';
    out[21] = ']';
    for (out[1..21], 0..) |*c, i| {
        c.* = if (i < pct / 5) '=' else ' ';
    }
    return out;
}

pub fn main() !void {
    var sub = Sub{};
    while (sub.depth < 100) {
        sub.dive(5);
        std.debug.print("\r{s} {d}%", .{ bar(sub.depth), sub.depth });
    }
    std.debug.print("\nsaw {d} fish and 1 octopus\n", .{sub.fish_seen});
}

